AssemblyGenerator::AssemblyGenerator() : nextOffset(4) {}

bool AssemblyGenerator::isNumber(const std::string& str) const {
    if (str.empty()) return false;
    std::size_t start = (str[0] == '-') ? 1 : 0;
    if (start >= str.length()) return false;

    for (std::size_t i = start; i < str.length(); ++i) {
        if (str[i] == '.') continue;
        if (!std::isdigit(static_cast<unsigned char>(str[i]))) return false;
    }
    return true;
}

int AssemblyGenerator::getOffset(const std::string& name) {
    auto it = stackOffsets.find(name);
    if (it != stackOffsets.end()) {
        return it->second;
    }
    int off = nextOffset;
    nextOffset += 4;
    stackOffsets[name] = off;
    return off;
}

std::string AssemblyGenerator::operandToX86(const std::string& operand) {
    if (operand == "true") {
        return "$1";
    }
    if (operand == "false") {
        return "$0";
    }
    if (isNumber(operand)) {
        long val = 0;
        try {
            val = static_cast<long>(std::stod(operand));
        } catch (...) {
            val = 0;
        }
        return "$" + std::to_string(val);
    }
    int off = getOffset(operand);
    return "-" + std::to_string(off) + "(%ebp)";
}

std::string AssemblyGenerator::generateX86(const std::vector<TACInstruction>& tacInstructions) {
    stackOffsets.clear();
    nextOffset = 4;

    for (const auto& inst : tacInstructions) {
        if (!inst.result.empty() && inst.op != TACOp::LABEL && inst.op != TACOp::GOTO &&
            inst.op != TACOp::IF_TRUE && inst.op != TACOp::IF_FALSE) {
            getOffset(inst.result);
        }
        if (!inst.arg1.empty() && !isNumber(inst.arg1) && inst.arg1 != "true" && inst.arg1 != "false") {
            getOffset(inst.arg1);
        }
        if (!inst.arg2.empty() && !isNumber(inst.arg2) && inst.arg2 != "true" && inst.arg2 != "false") {
            getOffset(inst.arg2);
        }
    }

    int totalStack = ((nextOffset + 15) / 16) * 16;
    if (totalStack < 32) totalStack = 32;

    std::ostringstream ss;
    ss << "# ==========================================================================\n";
    ss << "# Target Assembly: x86-32 AT&T (GNU as / MinGW GCC)\n";
    ss << "# Generated by Resilient Compiler Target Code Generator\n";
    ss << "# Stack Frame Size: " << totalStack << " bytes (aligned to 16 bytes)\n";
    ss << "# Variables & Temporaries Mapped to (%ebp) Stack Offsets\n";
    ss << "# ==========================================================================\n\n";

    ss << "    .file   \"resilientc_out.s\"\n";
    ss << "    .section .rdata,\"dr\"\n";
    ss << ".LC_fmt_int:\n";
    ss << "    .ascii  \"%d\\12\\0\"\n";
    ss << "    .text\n";
    ss << "    .globl  _main\n";
    ss << "    .def    _main; .scl 2; .type 32; .endef\n";
    ss << "_main:\n";
    ss << "    # --- Function Prologue ---\n";
    ss << "    pushl   %ebp\n";
    ss << "    movl    %esp, %ebp\n";
    ss << "    andl    $-16, %esp\n";
    ss << "    subl    $" << totalStack << ", %esp\n\n";

    for (std::size_t i = 0; i < tacInstructions.size(); ++i) {
        const auto& inst = tacInstructions[i];
        ss << "    # TAC: " << inst.toString() << "\n";

        switch (inst.op) {
            case TACOp::LABEL:
                ss << "." << inst.result << ":\n";
                break;

            case TACOp::GOTO:
                ss << "    jmp     ." << inst.result << "\n";
                break;

            case TACOp::IF_TRUE:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    cmpl    $0, %eax\n";
                ss << "    jne     ." << inst.result << "\n";
                break;

            case TACOp::IF_FALSE:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    cmpl    $0, %eax\n";
                ss << "    je      ." << inst.result << "\n";
                break;

            case TACOp::ASSIGN:
                if (isNumber(inst.arg1) || inst.arg1 == "true" || inst.arg1 == "false") {
                    ss << "    movl    " << operandToX86(inst.arg1) << ", "
                       << operandToX86(inst.result) << "\n";
                } else {
                    ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                    ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                }
                break;

            case TACOp::ADD:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    addl    " << operandToX86(inst.arg2) << ", %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::SUB:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    subl    " << operandToX86(inst.arg2) << ", %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::MUL:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    imull   " << operandToX86(inst.arg2) << ", %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::DIV:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    cltd\n";
                ss << "    movl    " << operandToX86(inst.arg2) << ", %ecx\n";
                ss << "    idivl   %ecx\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::MOD:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    cltd\n";
                ss << "    movl    " << operandToX86(inst.arg2) << ", %ecx\n";
                ss << "    idivl   %ecx\n";
                ss << "    movl    %edx, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::NEG:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    negl    %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::EQ:
            case TACOp::NE:
            case TACOp::LT:
            case TACOp::GT:
            case TACOp::LE:
            case TACOp::GE: {
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    cmpl    " << operandToX86(inst.arg2) << ", %eax\n";
                std::string setcc;
                if (inst.op == TACOp::EQ) setcc = "sete";
                else if (inst.op == TACOp::NE) setcc = "setne";
                else if (inst.op == TACOp::LT) setcc = "setl";
                else if (inst.op == TACOp::GT) setcc = "setg";
                else if (inst.op == TACOp::LE) setcc = "setle";
                else if (inst.op == TACOp::GE) setcc = "setge";
                ss << "    " << setcc << "    %al\n";
                ss << "    movzbl  %al, %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;
            }

            case TACOp::AND:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    andl    " << operandToX86(inst.arg2) << ", %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::OR:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    orl     " << operandToX86(inst.arg2) << ", %eax\n";
                ss << "    movl    %eax, " << operandToX86(inst.result) << "\n";
                break;

            case TACOp::PRINT:
                ss << "    movl    " << operandToX86(inst.arg1) << ", %eax\n";
                ss << "    pushl   %eax\n";
                ss << "    pushl   $.LC_fmt_int\n";
                ss << "    call    _printf\n";
                ss << "    addl    $8, %esp\n";
                break;
        }
        ss << "\n";
    }

    ss << "    # --- Function Epilogue ---\n";
    ss << "    movl    $0, %eax\n";
    ss << "    leave\n";
    ss << "    ret\n";

    return ss.str();
}

std::string AssemblyGenerator::generateEducational(const std::vector<TACInstruction>& tacInstructions) {
    std::ostringstream ss;
    ss << "; ==========================================================================\n";
    ss << "; Target Assembly: Educational Register-Based Architecture (ISA-32)\n";
    ss << "; Instructions: LOAD, STORE, ADD, SUB, MUL, DIV, CMP, BR, BRZ, PRINT, HALT\n";
    ss << "; General Registers: R0, R1, R2, R3 (Scratch), R4, R5, R6 (Operands), R7 (Flag)\n";
    ss << "; ==========================================================================\n\n";

    for (std::size_t i = 0; i < tacInstructions.size(); ++i) {
        const auto& inst = tacInstructions[i];
        switch (inst.op) {
            case TACOp::LABEL:
                ss << inst.result << ":\n";
                break;
            case TACOp::GOTO:
                ss << "    BR       " << inst.result << "\n";
                break;
            case TACOp::IF_TRUE:
                ss << "    LOAD     R0, [" << inst.arg1 << "]\n";
                ss << "    CMP      R0, #0\n";
                ss << "    BRNZ     " << inst.result << "\n";
                break;
            case TACOp::IF_FALSE:
                ss << "    LOAD     R0, [" << inst.arg1 << "]\n";
                ss << "    CMP      R0, #0\n";
                ss << "    BRZ      " << inst.result << "\n";
                break;
            case TACOp::ASSIGN:
                if (isNumber(inst.arg1)) {
                    ss << "    LOAD     R0, #" << inst.arg1 << "\n";
                } else {
                    ss << "    LOAD     R0, [" << inst.arg1 << "]\n";
                }
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::ADD:
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    LOAD     R2, " << (isNumber(inst.arg2) ? "#" : "[") << inst.arg2 << (isNumber(inst.arg2) ? "" : "]") << "\n";
                ss << "    ADD      R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::SUB:
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    LOAD     R2, " << (isNumber(inst.arg2) ? "#" : "[") << inst.arg2 << (isNumber(inst.arg2) ? "" : "]") << "\n";
                ss << "    SUB      R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::MUL:
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    LOAD     R2, " << (isNumber(inst.arg2) ? "#" : "[") << inst.arg2 << (isNumber(inst.arg2) ? "" : "]") << "\n";
                ss << "    MUL      R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::DIV:
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    LOAD     R2, " << (isNumber(inst.arg2) ? "#" : "[") << inst.arg2 << (isNumber(inst.arg2) ? "" : "]") << "\n";
                ss << "    DIV      R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::MOD:
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    LOAD     R2, " << (isNumber(inst.arg2) ? "#" : "[") << inst.arg2 << (isNumber(inst.arg2) ? "" : "]") << "\n";
                ss << "    MOD      R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::NEG:
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    NEG      R0, R1\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::EQ:
            case TACOp::NE:
            case TACOp::LT:
            case TACOp::GT:
            case TACOp::LE:
            case TACOp::GE: {
                ss << "    LOAD     R1, " << (isNumber(inst.arg1) ? "#" : "[") << inst.arg1 << (isNumber(inst.arg1) ? "" : "]") << "\n";
                ss << "    LOAD     R2, " << (isNumber(inst.arg2) ? "#" : "[") << inst.arg2 << (isNumber(inst.arg2) ? "" : "]") << "\n";
                std::string cmpName = "CMP_EQ";
                if (inst.op == TACOp::NE) cmpName = "CMP_NE";
                else if (inst.op == TACOp::LT) cmpName = "CMP_LT";
                else if (inst.op == TACOp::GT) cmpName = "CMP_GT";
                else if (inst.op == TACOp::LE) cmpName = "CMP_LE";
                else if (inst.op == TACOp::GE) cmpName = "CMP_GE";
                ss << "    " << cmpName << "   R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            }
            case TACOp::AND:
                ss << "    LOAD     R1, [" << inst.arg1 << "]\n";
                ss << "    LOAD     R2, [" << inst.arg2 << "]\n";
                ss << "    AND      R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::OR:
                ss << "    LOAD     R1, [" << inst.arg1 << "]\n";
                ss << "    LOAD     R2, [" << inst.arg2 << "]\n";
                ss << "    OR       R0, R1, R2\n";
                ss << "    STORE    [" << inst.result << "], R0\n";
                break;
            case TACOp::PRINT:
                ss << "    LOAD     R0, [" << inst.arg1 << "]\n";
                ss << "    PRINT    R0\n";
                break;
        }
    }
    ss << "    HALT\n";
    return ss.str();
}

bool AssemblyGenerator::writeAssemblyFile(const std::string& filename, const std::string& asmCode) {
    std::ofstream out(filename);
    if (!out.is_open()) return false;
    out << asmCode;
    return true;
}

bool AssemblyGenerator::assembleAndRun(const std::string& asmCode, std::string& programOutput, int& exitCode) {
    std::string sFile = "_rc_target_gen.s";
    std::string exeFile = "_rc_target_gen.exe";
    std::string logFile = "_rc_target_gen.log";

    if (!writeAssemblyFile(sFile, asmCode)) {
        programOutput = "Failed to write target assembly file.";
        exitCode = -1;
        return false;
    }

    std::string compileCmd = "gcc " + sFile + " -o " + exeFile + " > " + logFile + " 2>&1";
    int compileStatus = std::system(compileCmd.c_str());

    if (compileStatus != 0) {
        std::ifstream lf(logFile);
        std::string errStr((std::istreambuf_iterator<char>(lf)), std::istreambuf_iterator<char>());
        programOutput = "GCC Assembly/Link Error (exit " + std::to_string(compileStatus) + "):\n" + errStr;
        exitCode = compileStatus;
        std::remove(sFile.c_str());
        std::remove(logFile.c_str());
        return false;
    }

    std::string runCmd = exeFile + " > " + logFile + " 2>&1";
    exitCode = std::system(runCmd.c_str());

    std::ifstream rf(logFile);
    std::string outStr((std::istreambuf_iterator<char>(rf)), std::istreambuf_iterator<char>());
    programOutput = outStr;

    // Clean up temporary files
    std::remove(sFile.c_str());
    std::remove(exeFile.c_str());
    std::remove(logFile.c_str());
    return true;
}
